#import "SPClipboardManager.h"
#import <AppKit/AppKit.h>
#import <signal.h>
#import <unistd.h>

// Clipboard backup in a disposable child process, the concealed-item rule and the
// type allowlist are ported from giga-pisar (https://github.com/moznoazachem/giga-pisar,
// commits cc15efd and 9cf1def), MIT License, Copyright (c) 2026 moznoazachem.
// The license text and what was taken are in THIRD_PARTY.md.

const NSUInteger SPClipboardBackupMaxBytes = 16 * 1024 * 1024;
NSString *const SPClipboardSnapshotChildFlag = @"--velikiy-moguchiy-pb-snapshot";

static NSString *const kConcealedType = @"org.nspasteboard.ConcealedType";
static NSString *const kTransientType = @"org.nspasteboard.TransientType";
static NSString *const kAutoGeneratedType = @"org.nspasteboard.AutoGeneratedType";

// How long the app waits for the reader child before giving up on the backup
// (the paste then goes ahead without restoring the old clipboard).
static const NSTimeInterval kSnapshotDeadlineSeconds = 0.8;
// The child ends itself after this long even if the parent is gone.
static const unsigned kSnapshotChildLifetimeSeconds = 3;
static const NSUInteger kSnapshotMaxItems = 128;

// Child exit code for "cannot give a trustworthy snapshot" (over budget, too many
// items, or the clipboard changed under it).
static const int kChildExitUnusable = 2;

@interface SPClipboardManager ()

@property (nonatomic, strong) NSArray<NSPasteboardItem *> *backedUpItems;
@property (nonatomic, assign) NSInteger backedUpChangeCount;
@property (nonatomic, assign) NSInteger writtenChangeCount;
@property (nonatomic, assign) NSUInteger pendingRestoreGeneration;
@property (nonatomic, assign) BOOL hasBackup;

@end

@implementation SPClipboardManager

#pragma mark - Pure helpers

+ (BOOL)typesContainConcealed:(NSArray<NSString *> *)types {
    return [types containsObject:kConcealedType];
}

+ (BOOL)itemsContainConcealed:(NSArray<NSPasteboardItem *> *)items {
    for (NSPasteboardItem *item in items) {
        if ([self typesContainConcealed:item.types]) return YES;
    }
    return NO;
}

+ (NSSet<NSString *> *)backupTypeSet {
    static NSSet<NSString *> *set;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        set = [NSSet setWithArray:@[
            @"public.utf8-plain-text",
            @"public.utf16-external-plain-text",
            @"NSStringPboardType",
            @"public.rtf",
            @"public.html",
            @"public.png",
            @"public.file-url",
        ]];
    });
    return set;
}

+ (BOOL)isBackupType:(NSString *)type {
    return [[self backupTypeSet] containsObject:type];
}

+ (NSArray<NSString *> *)backupTypesFromTypes:(NSArray<NSString *> *)types {
    NSMutableArray<NSString *> *kept = [NSMutableArray array];
    for (NSString *type in types) {
        if ([self isBackupType:type]) [kept addObject:type];
    }
    return kept;
}

+ (BOOL)totalBytesWithinBudget:(NSUInteger)totalBytes {
    return totalBytes <= SPClipboardBackupMaxBytes;
}

#pragma mark - Disposable reader (child side)

+ (int)runSnapshotChildIfRequestedWithArgc:(int)argc argv:(const char *[])argv {
    if (argc != 3 || strcmp(argv[1], SPClipboardSnapshotChildFlag.UTF8String) != 0) return -1;
    @autoreleasepool {
        // Bounds the child's life: a hung provider call cannot be interrupted.
        signal(SIGALRM, SIG_DFL);
        alarm(kSnapshotChildLifetimeSeconds);

        NSPasteboard *pb = [NSPasteboard pasteboardWithName:@(argv[2])];
        NSInteger mark = pb.changeCount;
        NSMutableArray *items = [NSMutableArray array];
        BOOL concealed = NO;
        NSUInteger total = 0;

        NSArray<NSPasteboardItem *> *source = pb.pasteboardItems ?: @[];
        if ([self itemsContainConcealed:source]) {
            // Never read a password's bytes, not even to throw them away.
            concealed = YES;
        } else {
            if (source.count > kSnapshotMaxItems) _exit(kChildExitUnusable);
            for (NSPasteboardItem *item in source) {
                NSMutableArray *flavors = [NSMutableArray array];
                for (NSString *type in [self backupTypesFromTypes:item.types]) {
                    NSData *data = [item dataForType:type];
                    if (!data) continue;
                    total += data.length;
                    if (![self totalBytesWithinBudget:total]) _exit(kChildExitUnusable);
                    [flavors addObject:@{ @"type": type, @"data": data }];
                }
                if (flavors.count > 0) [items addObject:flavors];
            }
        }
        // Items were dropped entirely (only promises/private flavors): flag it,
        // the parent treats an unrepresentable clipboard as "no backup".
        BOOL lossy = !concealed && source.count > 0 && items.count == 0;

        if (pb.changeCount != mark) _exit(kChildExitUnusable);
        NSDictionary *payload = @{
            @"mark": @(mark),
            @"concealed": @(concealed),
            @"lossy": @(lossy),
            @"items": items,
        };
        NSError *error = nil;
        NSData *plist = [NSPropertyListSerialization dataWithPropertyList:payload
                                                                    format:NSPropertyListBinaryFormat_v1_0
                                                                   options:0
                                                                     error:&error];
        if (!plist || plist.length > SPClipboardBackupMaxBytes + 1024 * 1024) _exit(kChildExitUnusable);
        fwrite(plist.bytes, 1, plist.length, stdout);
        fflush(stdout);
    }
    return 0;
}

#pragma mark - Disposable reader (parent side)

/// Runs the reader child against the general pasteboard. Returns the decoded
/// payload, or nil when it timed out, failed, or the clipboard is too big.
- (NSDictionary *)snapshotGeneralPasteboardInChild {
    NSString *executable = [NSBundle mainBundle].executablePath;
    if (executable.length == 0) return nil;

    NSTask *task = [[NSTask alloc] init];
    task.executableURL = [NSURL fileURLWithPath:executable];
    task.arguments = @[ SPClipboardSnapshotChildFlag, NSPasteboardNameGeneral ];
    NSPipe *pipe = [NSPipe pipe];
    task.standardOutput = pipe;
    task.standardInput = [NSFileHandle fileHandleWithNullDevice];
    task.standardError = [NSFileHandle fileHandleWithNullDevice];

    dispatch_semaphore_t exited = dispatch_semaphore_create(0);
    task.terminationHandler = ^(NSTask *ended) {
        dispatch_semaphore_signal(exited);
    };

    NSError *launchError = nil;
    if (![task launchAndReturnError:&launchError]) {
        NSLog(@"[VelikiyMoguchiy] Clipboard reader could not start: %@", launchError.localizedDescription);
        return nil;
    }
    [pipe.fileHandleForWriting closeFile];

    // Drain stdout concurrently: a large clipboard overflows the pipe buffer
    // and would deadlock a child that is still writing.
    __block NSData *output = nil;
    dispatch_semaphore_t done = dispatch_semaphore_create(0);
    NSFileHandle *reader = pipe.fileHandleForReading;
    dispatch_async(dispatch_get_global_queue(QOS_CLASS_USER_INITIATED, 0), ^{
        output = [reader readDataToEndOfFile];
        dispatch_semaphore_signal(done);
    });

    long timedOut = dispatch_semaphore_wait(
        done, dispatch_time(DISPATCH_TIME_NOW, (int64_t)(kSnapshotDeadlineSeconds * NSEC_PER_SEC)));
    if (timedOut) {
        NSLog(@"[VelikiyMoguchiy] Clipboard reader exceeded %.1fs (promised data?); skipping the backup",
              kSnapshotDeadlineSeconds);
        // SIGKILL ends the child, which closes the pipe and releases the
        // drain thread; the file handle must not be closed from here while
        // that thread is still reading it.
        if (task.isRunning) kill(task.processIdentifier, SIGKILL);
        return nil;
    }
    // stdout is at EOF, so the child is exiting. Wait for the exit status
    // without spinning the main run loop (-waitUntilExit would).
    if (dispatch_semaphore_wait(exited, dispatch_time(DISPATCH_TIME_NOW, (int64_t)(0.3 * NSEC_PER_SEC)))) {
        if (task.isRunning) kill(task.processIdentifier, SIGKILL);
        return nil;
    }
    if (task.terminationReason != NSTaskTerminationReasonExit || task.terminationStatus != 0) {
        NSLog(@"[VelikiyMoguchiy] Clipboard reader failed (status %d); skipping the backup", task.terminationStatus);
        return nil;
    }
    id decoded = output.length > 0
        ? [NSPropertyListSerialization propertyListWithData:output options:NSPropertyListImmutable
                                                      format:NULL error:NULL]
        : nil;
    return [decoded isKindOfClass:[NSDictionary class]] ? decoded : nil;
}

#pragma mark - Backup / write / restore

- (void)backup {
    // Keep the earliest un-restored backup. Without this guard, a second
    // recording that finalizes within the restore window would re-back-up the
    // clipboard while it still holds the app's own transcription, so the later
    // restore would put that text back instead of the user's original content.
    if (self.hasBackup) return;
    _lastBackupLostContent = NO;

    NSPasteboard *pb = [NSPasteboard generalPasteboard];
    NSInteger changeCountBefore = pb.changeCount;

    NSDictionary *snapshot = [self snapshotGeneralPasteboardInChild];
    if (!snapshot) {
        NSLog(@"[VelikiyMoguchiy] Clipboard not backed up (unreadable, too large or too slow); it will not be restored");
        _lastBackupLostContent = YES;
        return;
    }
    if ([snapshot[@"concealed"] boolValue]) {
        // A password manager's entry: neither keep a copy nor ever write it
        // back as a fresh clipboard item.
        NSLog(@"[VelikiyMoguchiy] Clipboard holds a concealed item; not backed up and not restored");
        return;
    }
    if ([snapshot[@"lossy"] boolValue]) {
        NSLog(@"[VelikiyMoguchiy] Clipboard holds only unsupported flavors; not backed up");
        _lastBackupLostContent = YES;
        return;
    }
    if ([snapshot[@"mark"] integerValue] != changeCountBefore || pb.changeCount != changeCountBefore) {
        NSLog(@"[VelikiyMoguchiy] Clipboard changed while it was being read; not backed up");
        return;
    }

    NSMutableArray<NSPasteboardItem *> *items = [NSMutableArray array];
    for (NSArray *flavors in snapshot[@"items"]) {
        NSPasteboardItem *item = [[NSPasteboardItem alloc] init];
        for (NSDictionary *flavor in flavors) {
            NSString *type = flavor[@"type"];
            NSData *data = flavor[@"data"];
            if ([type isKindOfClass:[NSString class]] && [data isKindOfClass:[NSData class]] &&
                [SPClipboardManager isBackupType:type]) {
                [item setData:data forType:type];
            }
        }
        if (item.types.count > 0) [items addObject:item];
    }
    self.backedUpChangeCount = changeCountBefore;
    self.backedUpItems = items;
    self.hasBackup = YES;
}

- (void)writeText:(NSString *)text {
    NSPasteboard *pb = [NSPasteboard generalPasteboard];
    [pb clearContents];
    [pb setString:text forType:NSPasteboardTypeString];
    self.writtenChangeCount = pb.changeCount;
}

- (void)writeTransientText:(NSString *)text {
    NSPasteboard *pb = [NSPasteboard generalPasteboard];
    [pb clearContents];
    NSPasteboardItem *item = [[NSPasteboardItem alloc] init];
    [item setString:text forType:NSPasteboardTypeString];
    [item setData:[NSData data] forType:kTransientType];
    [item setData:[NSData data] forType:kAutoGeneratedType];
    [pb writeObjects:@[ item ]];
    self.writtenChangeCount = pb.changeCount;
}

- (void)scheduleRestoreAfterDelay:(NSUInteger)delayMs {
    if (!self.hasBackup) return;

    NSUInteger generation = ++self.pendingRestoreGeneration;
    NSInteger expectedChangeCount = self.writtenChangeCount;
    dispatch_after(dispatch_time(DISPATCH_TIME_NOW, (int64_t)(delayMs * NSEC_PER_MSEC)),
                   dispatch_get_main_queue(), ^{
        [self restoreIfUnchangedExpectedChangeCount:expectedChangeCount generation:generation];
    });
}

- (void)cancelPendingRestore {
    self.pendingRestoreGeneration += 1;
    // Abandoning the pending restore means this backup is no longer owed back
    // to the clipboard (e.g. a rewrite/template result is meant to stay). Clear
    // it so the next session backs up the current clipboard afresh.
    self.backedUpItems = nil;
    self.hasBackup = NO;
}

- (void)restoreIfUnchangedExpectedChangeCount:(NSInteger)expectedChangeCount generation:(NSUInteger)generation {
    if (!self.hasBackup) return;
    if (generation != self.pendingRestoreGeneration) return;

    NSPasteboard *pb = [NSPasteboard generalPasteboard];

    // Only restore if the clipboard hasn't been modified since we wrote to it
    if (pb.changeCount != expectedChangeCount) {
        NSLog(@"[VelikiyMoguchiy] Clipboard changed since write, skipping restore");
        self.backedUpItems = nil;
        self.hasBackup = NO;
        return;
    }

    // Defence in depth: a concealed item is never written back (backup() does
    // not keep one, but nothing may re-publish a password as a new copy).
    if ([SPClipboardManager itemsContainConcealed:self.backedUpItems]) {
        NSLog(@"[VelikiyMoguchiy] Backup holds a concealed item; skipping restore");
        self.backedUpItems = nil;
        self.hasBackup = NO;
        return;
    }

    [pb clearContents];
    if (self.backedUpItems.count > 0) {
        [pb writeObjects:self.backedUpItems];
    }
    NSLog(@"[VelikiyMoguchiy] Clipboard restored%@", self.backedUpItems.count == 0 ? @" (was empty)" : @"");
    self.pendingRestoreGeneration += 1;
    self.backedUpItems = nil;
    self.hasBackup = NO;
}

@end
